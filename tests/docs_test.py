#!/usr/bin/env python3
"""The docs link to what exists and name what the tree has."""

import pathlib
import re
import subprocess
import unittest

from reference_docs import limits_page

ROOT = pathlib.Path(__file__).resolve().parents[1]
PAGES = [
    *sorted((ROOT / "docs").rglob("*.md")),
    *(ROOT / name for name in ("README.md", "SECURITY.md", "CONTRIBUTING.md")),
    *(ROOT / folder / "README.md" for folder in ("benchmarks", "deploy", "skills")),
]
# Where a name a page gives must be found.
CODE = ("src", "include", "web/src", "web/sheet", "web/public", "web/tests", "web/recordings")
CODE += ("deploy", "tests", "benchmarks", "skills", ".github", "cmake")
CODE += ("install.sh", "CMakeLists.txt", "CMakePresets.json", "web/package.json")

FENCE = re.compile(r"^```.*?^```", re.M | re.S)
LINK = re.compile(r"\]\(([^)\s]+)\)")
SPAN = re.compile(r"`([^`\n]+)`")
NAMES = (
    re.compile(r"\bUAGENT_[A-Z0-9_]+\b"),
    re.compile(r"(?<![\w-])--[a-z][a-z-]+"),
    re.compile(r"/api/[a-z_]+"),
    re.compile(r"\bk[A-Z][A-Za-z0-9]+\b"),
)
PATH = re.compile(r"^[\w.-]+(/[\w.-]+)+\.[a-z]{1,5}$")


def anchors(page):
    """GitHub's anchors of a page's headings."""
    found = set()
    for line in FENCE.sub("", page.read_text()).splitlines():
        if line.startswith("#"):
            title = re.sub(r"[`*_]|\[([^\]]*)\]\([^)]*\)", r"\1", line.lstrip("#").strip())
            found.add(re.sub(r"[^\w\- ]", "", title.lower()).replace(" ", "-"))
    return found


class DocsTest(unittest.TestCase):
    def test_limit_comments_describe_their_declaration(self):
        page = limits_page(
            "// A ratio.\ninline constexpr int kParts = 3, kTotal = 4;\n"
            'inline constexpr char kMarker[] = ".done";\n'
        )
        self.assertIn("| `kParts` | `3` | A ratio. |", page)
        self.assertIn("| `kTotal` | `4` | A ratio. |", page)
        self.assertIn('| `kMarker` | `".done"` |  |', page)

    def test_links_resolve(self):
        for page in PAGES:
            for link in LINK.findall(FENCE.sub("", page.read_text())):
                if re.match(r"[a-z]+:", link):
                    continue
                path, _, anchor = link.partition("#")
                target = (page.parent / path).resolve() if path else page
                with self.subTest(page=str(page.relative_to(ROOT)), link=link):
                    self.assertTrue(target.exists(), "no such file")
                    if anchor and target.suffix == ".md":
                        self.assertIn(anchor, anchors(target), "no such heading")

    def test_names_exist(self):
        files = subprocess.check_output(["git", "ls-files", "-z", *CODE], cwd=ROOT, text=True)
        code = "\n".join(
            (ROOT / name).read_text(errors="ignore") for name in files.split("\0") if name
        )
        tracked = set(subprocess.check_output(["git", "ls-files"], cwd=ROOT, text=True).split())
        top = {name.split("/")[0] for name in tracked if "/" in name}
        for page in PAGES:
            # A generated page is the registry's own words.
            if page.parent.name == "interfaces" and "Generated by" in page.read_text():
                continue
            for span in SPAN.findall(FENCE.sub("", page.read_text())):
                names = {name for pattern in NAMES for name in pattern.findall(span)}
                for name in names:
                    with self.subTest(page=str(page.relative_to(ROOT)), name=name):
                        self.assertIn(name, code, "named in the docs, not in the tree")
                # A path from the repository's root; one under ~/.uagent is not.
                if PATH.match(span) and span.split("/")[0] in top:
                    with self.subTest(page=str(page.relative_to(ROOT)), path=span):
                        self.assertIn(span, tracked, "no such file")


if __name__ == "__main__":
    unittest.main()
