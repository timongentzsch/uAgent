#!/usr/bin/env python3
"""Check docs/interfaces against the binary's registries, or write them anew."""

import argparse
import json
import os
import pathlib
import re
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "interfaces"
NOTE = "Generated by `tests/reference_docs.py` from {source}; edit that, not this page.\n"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(value):
    return f"`{cell(value)}`"


def table(head, rows):
    lines = ["| " + " | ".join(head) + " |", "|" + " --- |" * len(head)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def default_of(setting):
    value = setting["default"]
    if value == "":
        return "empty"
    if isinstance(value, bool):
        return "on" if value else "off"
    return code(value)


def range_of(setting):
    if "choices" in setting:
        return ", ".join(code(choice) for choice in setting["choices"])
    low, high = setting.get("minimum"), setting.get("maximum")
    if low is None and high is None:
        return ""
    return f"{'' if low is None else low}–{'' if high is None else high}"


def settings_page(settings):
    parts = [
        "# Settings\n",
        NOTE.format(source="the settings registry (`include/core/config_registry.h`)"),
        "A setting is saved under its key for all conversations or for one folder "
        "(`/config`, the web's Settings), or set for a process by its variable. "
        "Later wins: all conversations, this folder, environment, command line, this "
        "conversation. A change applies from the next message, or after a restart "
        "(`/restart`) where the last column says so.\n",
    ]
    categories = list(dict.fromkeys(setting["category"] for setting in settings))
    for category in categories:
        rows = [
            [
                code(s["key"]),
                code(s["name"]),
                default_of(s),
                range_of(s),
                ", ".join(s["scopes"]),
                "restart" if s["takes_effect"] == "restart-required" else "next message",
                cell(s["description"]),
            ]
            for s in settings
            if s["category"] == category
        ]
        parts += [
            f"## {category.capitalize()}\n",
            table(["Key", "Variable", "Default", "Range", "Scopes", "Applies", "What"], rows),
        ]
    return "\n".join(parts)


def cli_page(flags, commands):
    flag_rows = [
        [code(f["usage"]), code(f["setting"]) if "setting" in f else "", cell(f["description"])]
        for f in flags
    ]
    command_rows = [
        [
            code(c["usage"]),
            "terminal" if c["terminal"] else "terminal, web",
            cell(c["description"]),
        ]
        for c in commands
        if not c["alias"]
    ]
    return "\n".join(
        [
            "# Command line\n",
            NOTE.format(source="the flag and command registries (`src/cli/`, `src/app/`)"),
            "## Flags\n",
            table(["Flag", "Sets", "What"], flag_rows),
            "## Slash commands\n",
            "Typed into a conversation. A command the web has a control for is "
            "offered there as that control.\n",
            table(["Command", "In", "What"], command_rows),
        ]
    )


def kind_of(schema):
    if "enum" in schema:
        return " \\| ".join(code(value) for value in schema["enum"])
    kind = schema.get("type", "any")
    if isinstance(kind, list):
        kind = " or ".join(kind)
    if kind == "array":
        return f"array of {kind_of(schema.get('items', {}))}"
    return kind


def parameters(schema, prefix=""):
    """One row per property; an object's own properties follow it, dotted."""
    required = set(schema.get("required", []))
    rows = []
    for name, value in schema.get("properties", {}).items():
        rows.append(
            [
                code(prefix + name),
                kind_of(value),
                "yes" if name in required else "",
                cell(value.get("description", "")),
            ]
        )
        inner = value.get("items", value)
        if inner.get("properties"):
            rows += parameters(inner, f"{prefix}{name}.")
    return rows


def tools_page(tools):
    parts = [
        "# Tool schemas\n",
        NOTE.format(source="the tool definitions (`src/tools/`, `src/app/`)"),
        "Each built-in tool as a model is sent it: when it is offered, whether "
        "calls of it may run side by side, its description and its parameters.\n",
    ]
    for tool in tools:
        parts += [
            f"## {tool['name']}\n",
            f"Offered: {tool['when']}. Parallel: {'yes' if tool['parallel_safe'] else 'no'}.\n",
            tool["description"] + "\n",
        ]
        rows = parameters(tool["parameters"])
        if rows:
            parts.append(table(["Parameter", "Type", "Required", "What"], rows))
    return "\n".join(parts)


CONSTANT = re.compile(r"inline constexpr [\w:<> ]+? (k\w+(?:\[\])?\s*=\s*[^;]+);", re.S)
UNIT = re.compile(r"\b(KiB|MiB)\((\d+)\)")


def limits_page(header):
    """Every constant of limits.h with the comment above it."""
    rows, note = [], []
    statement = ""
    for line in header.splitlines():
        text = line.strip()
        if text.startswith("//") and not statement:
            note.append(text.lstrip("/ ").strip())
            continue
        if not text and not statement:
            note = []
            continue
        statement += " " + text
        if ";" not in text and "{" not in text:
            continue
        match = CONSTANT.search(statement)
        if match:
            for declaration in re.split(r",\s*(?=k\w+\s*=)", match.group(1)):
                name, value = declaration.split("=", 1)
                name = name.strip().removesuffix("[]")
                if name not in ("kKiB", "kMiB"):
                    value = UNIT.sub(r"\2 \1", " ".join(value.split()))
                    rows.append([code(name), code(value), cell(" ".join(note))])
        note = []
        statement = ""
    return "\n".join(
        [
            "# Limits\n",
            NOTE.format(source="`include/core/limits.h`"),
            "Limits fixed in the binary. A limit a person can change is a "
            "[setting](settings.md).\n",
            table(["Constant", "Value", "What"], rows),
        ]
    )


def pages(binary):
    with tempfile.TemporaryDirectory() as home:
        reference = json.loads(
            subprocess.check_output(
                [binary, "--control", '{"kind":"reference"}'],
                env={"HOME": home, "PATH": os.environ.get("PATH", "")},
            )
        )
    return {
        "settings.md": settings_page(reference["settings"]),
        "cli.md": cli_page(reference["flags"], reference["commands"]),
        "tool-schemas.md": tools_page(reference["tools"]),
        "limits.md": limits_page((ROOT / "include/core/limits.h").read_text()),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary")
    parser.add_argument("--write", action="store_true", help="write the pages instead of checking")
    args = parser.parse_args()
    stale = []
    for name, text in pages(args.binary).items():
        path = OUT / name
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        elif not path.exists() or path.read_text() != text:
            stale.append(name)
    if stale:
        raise SystemExit(
            f"docs/interfaces differs from the binary: {', '.join(stale)}. "
            f"Run: python3 tests/reference_docs.py {args.binary} --write"
        )


if __name__ == "__main__":
    main()
